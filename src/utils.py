def get_qe_prefix(self):
    return getattr(self, "qe_bin_prefix", None) or os.environ.get("QE_BIN_PREFIX", "")


def read_qe_cutoffs(in_path: str) -> Dict[str, str]:
    """Read ecutwfc/ecutrho out of a QE input, so later steps in the same run can
    be pinned to the values the SCF actually used."""
    out: Dict[str, str] = {}
    try:
        with open(in_path, "r", encoding="utf-8") as f:
            text = f.read()
    except OSError:
        return out
    for key in ("ecutwfc", "ecutrho"):
        m = re.search(rf"^[ \t]*{key}[ \t]*=[ \t]*([^,\s]+)", text, re.IGNORECASE | re.MULTILINE)
        if m:
            out[key] = m.group(1)
    return out


def _set_or_insert_control_key(text: str, key: str, value: str) -> str:
    """Set `key='value'` in the first namelist of a QE input, inserting the line
    if it isn't there.

    A plain regex substitution silently no-ops when the key is absent, which for
    `prefix` means QE falls back to its 'pwscf' default — fine on its own, but it
    breaks as soon as one step in a chain writes an explicit prefix and another
    doesn't. Inserting guarantees every step agrees.

    Post-processing inputs (bands.x, dos.x, ...) have no &control; their single
    namelist (&BANDS, &DOS, ...) is where prefix belongs, so we target whichever
    namelist opens first rather than hard-coding &control.
    """
    pattern = re.compile(
        rf"(^[ \t]*{re.escape(key)}[ \t]*=[ \t]*)(?:['\"]?)([^,'\"\n]*)(?:['\"]?)([ \t]*,?)[ \t]*$",
        re.IGNORECASE | re.MULTILINE,
    )
    if pattern.search(text):
        return pattern.sub(rf"\1'{value}'\3", text)

    # Not present — insert just after the first namelist opener.
    lines = text.splitlines()
    for i, line in enumerate(lines):
        if re.match(r"^[ \t]*&\w+", line):
            indent = re.match(r"^[ \t]*", line).group(0) + "  "
            lines.insert(i + 1, f"{indent}{key} = '{value}',")
            return "\n".join(lines) + ("\n" if text.endswith("\n") else "")
    return text

def patch_qe_input_file(
    in_path: str,
    *,
    new_pseudo_dir: Optional[str] = None,
    new_outdir: Optional[str] = None,
    new_prefix: Optional[str] = None,
    # Pseudopotential replacement policy (choose one or both; pp_map has higher priority):
    pp_dir: Optional[str] = None,          # replace the 3rd column .UPF file with pp_dir/original-filename
    pp_map: Optional[Dict[str, str]] = None,  # species name -> pseudopotential file path (absolute or relative)
    pp_dir_clean: Optional[bool] = False,
    force_new_step: bool = False,
    new_input_dft: Optional[str] = None,
    new_cutoffs: Optional[Dict[str, str]] = None,   # {"ecutwfc": "80", "ecutrho": "320"}
) -> None:
    """
    In-place modification of QE input file:
    1) Replace pseudo_dir/outdir/prefix values if provided.
    2) In ATOMIC_SPECIES block, replace the 3rd column (.UPF file):
       - with pp_dir/filename if pp_dir is given, or
       - with pp_map[species] if provided (pp_map has higher priority).
    """
    with open(in_path, "r", encoding="utf-8") as f:
        text = f.read()

    def _replace_key(text: str, key: str, value: str) -> str:
        # Match lines like  key = '...'  or  key='...'  or  key = ... (possibly ending with a comma)
        # Try to preserve trailing comments
        pattern = re.compile(
            rf"(^\s*{re.escape(key)}\s*=\s*)(?:['\"]?)([^,'\"\n]+)(?:['\"]?)(\s*,?\s*)(?=$)",
            re.IGNORECASE | re.MULTILINE
        )
        # If no match, try a more relaxed version (allowing trailing comments)
        if not pattern.search(text):
            pattern = re.compile(
                rf"(^\s*{re.escape(key)}\s*=\s*)(?:['\"]?)([^,'\"\n]+)(?:['\"]?)(\s*,?\s*)(?=.*$)",
                re.IGNORECASE | re.MULTILINE
            )
        return pattern.sub(rf"\1'{value}'\3", text)

    # Always force pseudo_dir to the config-resolved absolute path — the LLM
    # often writes a relative one like '../PseudoDojo/...' that breaks once
    # the run's cwd is nested deeper than a single layer.
    if new_pseudo_dir:
        text = _replace_key(text, "pseudo_dir", new_pseudo_dir)
    if new_outdir:
        text = _replace_key(text, "outdir", new_outdir)
    if force_new_step and re.search(r"(?mi)^\s*restart_mode\s*=", text):
        text = _replace_key(text, "restart_mode", "from_scratch")
    # Force a single prefix across every step of a run. QE chains steps through
    # <outdir>/<prefix>.save: nscf/bands read the SCF charge density from it, and
    # bands.x reads the bands run's wavefunctions from it. Each step's input is
    # generated by an independent LLM call that cannot know what prefix the
    # previous step picked, so leaving this to the model silently breaks the
    # chain (bands.x reads a stale or nonexistent .save and emits garbage).
    if new_prefix:
        text = _set_or_insert_control_key(text, "prefix", new_prefix)
    # Same reasoning as prefix: nscf/bands runs read the SCF charge density, so
    # their plane-wave cutoffs MUST match the SCF run that produced it. Each
    # step's input comes from an independent LLM call that cannot see the earlier
    # file, so asking the model to "reuse the same cutoffs" does not hold — it
    # drifts (e.g. ecutrho 320 -> 360 on the bands step). Pin them numerically.
    # Keep input_dft consistent with the pseudopotential library. Pointing at the
    # LDA library while leaving input_dft='PBE' is not an error QE refuses — it
    # overrides the pseudo's own functional and quietly computes with a
    # mismatched one, which is worse than failing. Only rewrite the key when it
    # is already present; when absent QE takes the functional from the UPF, which
    # is what we want.
    if new_input_dft:
        pattern = re.compile(
            r"(^[ \t]*input_dft[ \t]*=[ \t]*)(?:['\"]?)([^,'\"\n]*)(?:['\"]?)",
            re.IGNORECASE | re.MULTILINE,
        )
        if pattern.search(text):
            text = pattern.sub(rf"\1'{new_input_dft}'", text)

    if new_cutoffs:
        for key, value in new_cutoffs.items():
            pattern = re.compile(
                rf"(^[ \t]*{re.escape(key)}[ \t]*=[ \t]*)([^,\s]+)",
                re.IGNORECASE | re.MULTILINE,
            )
            if pattern.search(text):
                text = pattern.sub(rf"\g<1>{value}", text)

    # Process ATOMIC_SPECIES block
    lines = text.splitlines()
    new_lines: List[str] = []
    in_species = False

    # Keywords indicating the end of ATOMIC_SPECIES block
    species_end_keys = re.compile(
        r"^\s*(ATOMIC_POSITIONS|K_POINTS|CELL_PARAMETERS|ATOMIC_FORCES|OCCUPATIONS|CONSTRAINTS|&\w+)\b",
        re.IGNORECASE
    )

    for raw in lines:
        line = raw
        if not in_species:
            if re.match(r"^\s*ATOMIC_SPECIES\b", line, re.IGNORECASE):
                in_species = True
                new_lines.append(line)
                continue
            else:
                new_lines.append(line)
                continue

        # Inside ATOMIC_SPECIES
        if not line.strip() or species_end_keys.match(line):
            in_species = False
            new_lines.append(line)
            continue

        # Preserve inline comments (after '#')
        parts = line.split("#", 1)
        body = parts[0].rstrip()
        comment = (" #"+parts[1]) if len(parts) == 2 else ""

        # Expected format: species mass pseudopotential
        tokens = body.split()
        if len(tokens) >= 3:
            species, mass, ppfile = tokens[:3]
            # Only modify .upf files
            if ppfile.lower().endswith(".upf"):
                new_pp = ppfile
                # Priority: pp_dir_clean > pp_map > pp_dir
                if pp_dir_clean:
                    new_pp = f"{species}.upf".lower()
                elif pp_map and species in pp_map:
                    new_pp = pp_map[species]
                elif pp_dir:
                    new_pp = os.path.join(pp_dir, os.path.basename(ppfile))
                # Rebuild line (preserve extra tokens if present)
                rest = " ".join(tokens[3:]) if len(tokens) > 3 else ""
                rebuilt = f"{species} {mass} {new_pp}"
                if rest:
                    rebuilt += " " + rest
                line = rebuilt + comment
            else:
                line = body + comment
        else:
            line = raw

        new_lines.append(line)

    new_text = "\n".join(new_lines)
    if new_text != text:
        with open(in_path, "w", encoding="utf-8") as f:
            f.write(new_text)


def validate_pseudos_exist(in_path: str) -> Tuple[None, Optional[str]]:
    """Scan a QE input file's ATOMIC_SPECIES block and check that each
    referenced .upf exists under the file's pseudo_dir.

    Catches the (otherwise obscure) "rc=132 / mpirun cannot exec" failure
    when the selected pseudo library doesn't ship the element the LLM
    asked for (e.g. requesting Eu/Nd against PBE_standard which stops at
    Lu). Returns (None, "<error message>") on missing files so the agent
    can retry with different params instead of crashing pw.x.
    """
    try:
        with open(in_path, "r", encoding="utf-8") as f:
            text = f.read()
    except OSError as e:
        return None, f"could not read input file: {e}"

    pd_match = re.search(
        r"^\s*pseudo_dir\s*=\s*['\"]([^'\"]+)['\"]",
        text,
        re.IGNORECASE | re.MULTILINE,
    )
    if not pd_match:
        return None, None  # nothing to validate
    pseudo_dir = pd_match.group(1)
    if not os.path.isdir(pseudo_dir):
        return None, f"pseudo_dir does not exist on disk: {pseudo_dir}"

    species_end_keys = re.compile(
        r"^\s*(ATOMIC_POSITIONS|K_POINTS|CELL_PARAMETERS|ATOMIC_FORCES|OCCUPATIONS|CONSTRAINTS|&\w+)\b",
        re.IGNORECASE,
    )
    in_species = False
    missing: List[str] = []
    for raw in text.splitlines():
        if not in_species:
            if re.match(r"^\s*ATOMIC_SPECIES\b", raw, re.IGNORECASE):
                in_species = True
            continue
        if not raw.strip() or species_end_keys.match(raw):
            break
        body = raw.split("#", 1)[0].strip()
        tokens = body.split()
        if len(tokens) < 3:
            continue
        ppfile = tokens[2]
        if not ppfile.lower().endswith(".upf"):
            continue
        candidate = ppfile if os.path.isabs(ppfile) else os.path.join(pseudo_dir, ppfile)
        if not os.path.isfile(candidate):
            missing.append(ppfile)

    if missing:
        return None, (
            f"pseudopotential(s) not found in {pseudo_dir}: {', '.join(missing)}. "
            f"The selected library does not cover one of the requested elements."
        )
    return None, None


def package_pseudos_for_remote(
    input_paths: List[str],
    *,
    pseudo_dir: str,
    work_dir: str,
    package_dir_name: str = "pseudos",
) -> List[str]:
    """
    Copy only the pseudopotentials referenced by generated QE inputs into the
    run directory and patch inputs to use a relative pseudo_dir.

    Cluster jobs cannot see absolute paths from the local desktop, so remote
    packages must be self-contained:

        run_dir/input_*.in
        run_dir/slurm_job_*.sh
        run_dir/pseudos/*.upf
    """
    package_dir = Path(work_dir) / package_dir_name
    package_dir.mkdir(parents=True, exist_ok=True)

    copied: List[str] = []
    for input_path in input_paths:
        for pp_name in _qe_input_pseudo_filenames(input_path):
            src = Path(pp_name)
            if not src.is_absolute():
                src = Path(pseudo_dir) / pp_name
            if not src.is_file():
                raise FileNotFoundError(f"Could not package pseudopotential: {src}")
            dest = package_dir / src.name
            if not dest.exists():
                shutil.copy2(src, dest)
                copied.append(str(dest))

        patch_qe_input_file(
            input_path,
            new_pseudo_dir=f"./{package_dir_name}",
            pp_dir_clean=True,
        )

    return copied


def _qe_input_pseudo_filenames(in_path: str) -> List[str]:
    with open(in_path, "r", encoding="utf-8") as f:
        text = f.read()

    species_end_keys = re.compile(
        r"^\s*(ATOMIC_POSITIONS|K_POINTS|CELL_PARAMETERS|ATOMIC_FORCES|OCCUPATIONS|CONSTRAINTS|&\w+)\b",
        re.IGNORECASE,
    )
    in_species = False
    pp_files: List[str] = []
    for raw in text.splitlines():
        if not in_species:
            if re.match(r"^\s*ATOMIC_SPECIES\b", raw, re.IGNORECASE):
                in_species = True
            continue
        if not raw.strip() or species_end_keys.match(raw):
            break
        tokens = raw.split("#", 1)[0].strip().split()
        if len(tokens) >= 3 and tokens[2].lower().endswith(".upf"):
            pp_files.append(os.path.basename(tokens[2]))
    return pp_files


def parse_scripts_block(generated: str) -> list[str]:
    # Prefer explicit <script>...</script> tags when the model follows the
    # prompt exactly.
    scripts = re.findall(
        r"<script>(.*?)</script>|<script>(.*?)<\\script>",
        generated,
        flags=re.DOTALL | re.IGNORECASE,
    )

    # normalize
    normalized = [(s[0] if s[0] else s[1]).strip() for s in scripts]

    if not normalized:
        normalized = _fallback_script_blocks(generated)

    normalized = [s.replace("\\n", "\n") for s in normalized]

    return normalized


def _fallback_script_blocks(generated: str) -> list[str]:
    text = (generated or "").strip()
    if not text:
        raise ValueError("No <script>...</script> blocks found in model output.")

    fence_matches = re.findall(r"```(?:[a-zA-Z0-9_-]+)?\s*(.*?)```", text, flags=re.DOTALL)
    candidates = [_extract_qe_input_region(m) for m in fence_matches]
    candidates = [c for c in candidates if c]
    if candidates:
        return candidates

    json_candidates = _extract_qe_inputs_from_json(text)
    if json_candidates:
        return json_candidates

    unescaped = text.replace("\\n", "\n").replace('\\"', '"')
    extracted = _extract_qe_input_region(unescaped)
    if extracted:
        return [extracted]

    raise ValueError("No <script>...</script> blocks found in model output.")


def _looks_like_qe_input(text: str) -> bool:
    return bool(
        re.search(r"(?mi)^\s*&(?:control|system|electrons|ions|cell|inputpp|input|dos|bands)\b", text)
        or re.search(r"(?mi)^\s*(ATOMIC_SPECIES|K_POINTS|ATOMIC_POSITIONS)\b", text)
    )


def _extract_qe_inputs_from_json(text: str) -> list[str]:
    try:
        obj = json.loads(text)
    except Exception:
        return []

    found: list[str] = []

    def visit(value: Any) -> None:
        if isinstance(value, str):
            extracted = _extract_qe_input_region(value.replace("\\n", "\n").replace('\\"', '"'))
            if extracted:
                found.append(extracted)
        elif isinstance(value, list):
            for item in value:
                visit(item)
        elif isinstance(value, dict):
            for item in value.values():
                visit(item)

    visit(obj)
    return found


def _extract_qe_input_region(text: str) -> Optional[str]:
    if not text:
        return None

    marker = re.search(
        r"(?mi)^\s*(?:&(?:control|system|electrons|ions|cell|inputpp|input|inputph|dos|bands|projwfc)\b|"
        r"ATOMIC_SPECIES\b|ATOMIC_POSITIONS\b|K_POINTS\b)",
        text,
    )
    if not marker:
        return None

    candidate = text[marker.start():].strip()
    candidate = re.split(r"(?mi)^\s*(?:</?scripts?>|</?script>|```)\s*$", candidate)[0].strip()
    if _looks_like_qe_input(candidate):
        return candidate
    return None


TASK_STEMS = {
    "pw_vc_relax": "vc-relax", "pw_relax": "relax", "pw_scf": "scf",
    "pw_nscf": "nscf", "pw_bands": "bands", "bands_post": "bands-post",
    "dos_post": "dos", "projwfc_post": "pdos", "pp_post": "pp",
    "pw_phonon_gamma": "ph", "q2r_post": "q2r", "matdyn_post": "matdyn",
    "dynmat_post": "dynmat", "elastic_post": "ev",
}


def task_file_stem(step_index: int, tool: str) -> str:
    """Task-oriented stem for a step's files: 01_vc-relax, 07_ph, ...

    `input_7_1.in` tells a user nothing about what the file is; the zero-padded
    index keeps runs sorting correctly while the task name makes a downloaded
    bundle self-explanatory.
    """
    name = TASK_STEMS.get((tool or "").strip(), (tool or "step").strip() or "step")
    return f"{int(step_index):02d}_{name}"


def write_inputs(
    work_dir: str,
    scripts: list,
    prefix: str = "input",
    suffix: str = ".in",
    subproblem_id: Optional[int] = None,
    stem: Optional[str] = None,
):
    """
    write multiple input scripts to files in work_dir.
    """
    os.makedirs(work_dir, exist_ok=True)
    paths = []
    for idx, content in enumerate(scripts, start=1):
        if stem is not None:
            # Multiple inputs for one step get -1/-2 suffixes; a lone input keeps
            # the bare task name.
            tail = f"-{idx}" if len(scripts) > 1 else ""
            filename = f"{stem}{tail}{suffix}"
        elif subproblem_id is None:
            filename = f"{prefix}_{idx}{suffix}"
        else:
            filename = f"{prefix}_{subproblem_id}_{idx}{suffix}"
        path = os.path.join(work_dir, filename)
        with open(path, "w", encoding="utf-8") as f:
            f.write(content.rstrip() + "\n\n")
        paths.append(path)
    return paths

